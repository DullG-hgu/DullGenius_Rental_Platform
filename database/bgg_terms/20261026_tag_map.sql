WHERE gt.source = 'bgg'
  AND NOT EXISTS (SELECT 1 FROM public.game_bgg_terms l JOIN public.bgg_terms b ON b.id = l.term_id
                  WHERE l.game_id = gt.game_id AND b.tag_id = gt.tag_id);

